def body(doc, text, indent=False):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(11)
    if indent:
        p.paragraph_format.left_indent = Cm(0.75)
    p.paragraph_format.space_after = Pt(3)
    return p

def bullet(doc, text, color=None, bold_prefix=None):
    p = doc.add_paragraph(style='List Bullet')
    if bold_prefix:
        r1 = p.add_run(bold_prefix)
        r1.font.size = Pt(11)
        r1.font.bold = True
        if color:
            r1.font.color.rgb = RGBColor(*color)
    r2 = p.add_run(text)
    r2.font.size = Pt(11)
    if color and not bold_prefix:
        r2.font.color.rgb = RGBColor(*color)
    p.paragraph_format.space_after = Pt(3)
    return p

def bold_body(doc, label, text, label_color=None):
    p = doc.add_paragraph()
    r1 = p.add_run(label)
    r1.font.size = Pt(11)
    r1.font.bold = True
    if label_color:
        r1.font.color.rgb = RGBColor(*label_color)
    r2 = p.add_run(text)
    r2.font.size = Pt(11)
    p.paragraph_format.space_after = Pt(3)
    return p

def code_block(doc, text, color=None):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.75)
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(4)
    run = p.add_run(text)
    run.font.size = Pt(10)
    run.font.name = 'Courier New'
    if color:
        run.font.color.rgb = RGBColor(*color)
    else:
        run.font.color.rgb = RGBColor(0x1F, 0x49, 0x7D)
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement('w:pBdr')
    for side in ['top', 'bottom', 'left', 'right']:
        el = OxmlElement(f'w:{side}')
        el.set(qn('w:val'), 'single')
        el.set(qn('w:sz'), '4')
        el.set(qn('w:space'), '4')
        el.set(qn('w:color'), 'CCCCCC')
        pBdr.append(el)
    pPr.append(pBdr)
    return p

